def translate(text: str, lang: str = DEFAULT_LANGUAGE) -> str:
    if lang == "hi":
        return HI.get(text, text)
    return text


def reason_label(code: str, lang: str = DEFAULT_LANGUAGE) -> str:
    entry = REASON_TEXT.get(code)
    if not entry:
        return code.replace("_", " ").capitalize()
    return entry.get(lang) or entry["en"]


